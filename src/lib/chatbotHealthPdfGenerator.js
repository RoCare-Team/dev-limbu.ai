/**
 * chatbotHealthPdfGenerator.js
 *
 * Server-side PDF report generator for GMB Health Score.
 * Uses pdfkit (Node.js, no browser DOM required).
 *
 * Returns a Buffer that can be uploaded directly to S3.
 */

import PDFDocument from "pdfkit";

// ── Brand colours ────────────────────────────────────────────────────────────
const COLOR = {
  primary:    "#1A73E8", // Google Blue
  dark:       "#1C1C1E",
  muted:      "#6B7280",
  light:      "#F3F4F6",
  success:    "#16A34A",
  warning:    "#D97706",
  danger:     "#DC2626",
  accent:     "#8B5CF6",
  white:      "#FFFFFF",
  border:     "#E5E7EB",
};

/**
 * Map a numeric score (0-100) to a colour and label.
 */
function scoreStyle(score) {
  if (score >= 80) return { color: COLOR.success, label: "Excellent" };
  if (score >= 60) return { color: COLOR.primary,  label: "Good"      };
  if (score >= 40) return { color: COLOR.warning,  label: "Average"   };
  return               { color: COLOR.danger,   label: "Needs Work" };
}

/**
 * Draw a filled rounded rectangle.
 */
function roundedRect(doc, x, y, w, h, r, fillColor) {
  doc.save().roundedRect(x, y, w, h, r).fill(fillColor).restore();
}

/**
 * Draw a single metric card.
 *  x, y = top-left; w = width; h = height
 */
function metricCard(doc, x, y, w, h, label, value, color) {
  roundedRect(doc, x, y, w, h, 8, COLOR.light);
  doc
    .fontSize(9)
    .fillColor(COLOR.muted)
    .text(label, x + 10, y + 10, { width: w - 20 });
  doc
    .fontSize(20)
    .fillColor(color || COLOR.dark)
    .text(String(value ?? "—"), x + 10, y + 26, { width: w - 20 });
}

/**
 * Generate a GMB Health Score PDF report.
 *
 * @param {object} opts
 * @param {string}      opts.businessName   - e.g. "Sharma Medical Store"
 * @param {string}      opts.address        - e.g. "Connaught Place, Delhi"
 * @param {number|null} opts.score          - 0–100 (null = unavailable)
 * @param {object}      opts.rawData        - Full n8n response (for extra detail)
 * @param {string}      opts.generatedAt    - ISO date string
 *
 * @returns {Promise<Buffer>}  PDF as a Node.js Buffer
 */
export function generateHealthScorePdf(opts) {
  const {
    businessName = "Your Business",
    address      = "",
    score        = null,
    rawData      = {},
    generatedAt  = new Date().toISOString(),
  } = opts;

  return new Promise((resolve, reject) => {
    const chunks = [];
    const doc = new PDFDocument({
      size:    "A4",
      margins: { top: 40, bottom: 40, left: 40, right: 40 },
      info: {
        Title:   `GMB Health Score — ${businessName}`,
        Author:  "Limbu AI",
        Subject: "Google Business Profile Health Report",
      },
    });

    doc.on("data",  (chunk) => chunks.push(chunk));
    doc.on("end",   ()      => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    const PAGE_W = doc.page.width  - 80; // usable width (margins subtracted)
    const L      = 40;                   // left margin

    // ── HEADER BANNER ────────────────────────────────────────────────────────
    roundedRect(doc, 0, 0, doc.page.width, 110, 0, COLOR.primary);

    doc
      .fontSize(22)
      .fillColor(COLOR.white)
      .font("Helvetica-Bold")
      .text("GMB Health Score Report", L, 22, { width: PAGE_W });

    doc
      .fontSize(11)
      .font("Helvetica")
      .fillColor("rgba(255,255,255,0.85)")
      .text(businessName, L, 52, { width: PAGE_W });

    if (address) {
      doc
        .fontSize(9)
        .fillColor("rgba(255,255,255,0.7)")
        .text(address, L, 68, { width: PAGE_W });
    }

    doc
      .fontSize(8)
      .fillColor("rgba(255,255,255,0.6)")
      .text(`Generated by Limbu AI  •  ${new Date(generatedAt).toLocaleDateString("en-IN", {
        day: "2-digit", month: "short", year: "numeric",
      })}`, L, 88, { width: PAGE_W });

    // ── SCORE CIRCLE SECTION ─────────────────────────────────────────────────
    const circleTop = 130;
    const circleX   = doc.page.width / 2;
    const circleR   = 70;
    const style     = scoreStyle(score ?? 0);

    // Outer ring
    doc
      .circle(circleX, circleTop + circleR, circleR + 8)
      .lineWidth(3)
      .strokeColor(style.color)
      .stroke();

    // Inner fill
    doc
      .circle(circleX, circleTop + circleR, circleR)
      .fillColor(COLOR.white)
      .fill();

    // Score number
    if (score !== null) {
      doc
        .fontSize(48)
        .fillColor(style.color)
        .font("Helvetica-Bold")
        .text(String(score), circleX - circleR, circleTop + 28, {
          width: circleR * 2,
          align: "center",
        });
      doc
        .fontSize(11)
        .fillColor(COLOR.muted)
        .font("Helvetica")
        .text("/ 100", circleX - circleR, circleTop + 86, {
          width: circleR * 2,
          align: "center",
        });
    } else {
      doc
        .fontSize(24)
        .fillColor(COLOR.muted)
        .text("N/A", circleX - circleR, circleTop + 50, {
          width: circleR * 2,
          align: "center",
        });
    }

    // Grade label badge
    const badgeY = circleTop + circleR * 2 + 18;
    roundedRect(doc, circleX - 50, badgeY, 100, 28, 14, style.color);
    doc
      .fontSize(13)
      .fillColor(COLOR.white)
      .font("Helvetica-Bold")
      .text(style.label, circleX - 50, badgeY + 7, { width: 100, align: "center" });

    // ── METRIC CARDS ─────────────────────────────────────────────────────────
    const cardTop = badgeY + 50;
    const cardH   = 68;
    const cardW   = (PAGE_W - 20) / 3;

    const metrics = [
      {
        label: "Profile Completeness",
        value: rawData.profileCompleteness ?? rawData.profile_completeness ?? "—",
        color: COLOR.primary,
      },
      {
        label: "Review Rating",
        value: rawData.rating ?? rawData.averageRating ?? "—",
        color: COLOR.accent,
      },
      {
        label: "Total Reviews",
        value: rawData.totalReviews ?? rawData.reviewCount ?? "—",
        color: COLOR.success,
      },
    ];

    metrics.forEach((m, i) => {
      metricCard(doc, L + i * (cardW + 10), cardTop, cardW, cardH, m.label, m.value, m.color);
    });

    // ── ISSUES SECTION ───────────────────────────────────────────────────────
    const issueTop = cardTop + cardH + 24;
    const issues   = extractIssues(rawData);

    if (issues.length) {
      doc
        .fontSize(14)
        .fillColor(COLOR.dark)
        .font("Helvetica-Bold")
        .text("Issues Found", L, issueTop);

      doc.moveDown(0.3);

      issues.forEach((issue, idx) => {
        const y = doc.y;
        // Bullet dot
        doc.circle(L + 6, y + 5, 4).fill(COLOR.danger);
        doc
          .fontSize(10)
          .fillColor(COLOR.dark)
          .font("Helvetica")
          .text(issue, L + 18, y, { width: PAGE_W - 18 });
        doc.moveDown(0.4);
      });
    }

    // ── RECOMMENDATIONS ──────────────────────────────────────────────────────
    const recTop = doc.y + 16;
    const recs   = extractRecommendations(rawData, score);

    doc
      .fontSize(14)
      .fillColor(COLOR.dark)
      .font("Helvetica-Bold")
      .text("Recommendations", L, recTop);

    doc.moveDown(0.3);

    recs.forEach((rec, idx) => {
      const y = doc.y;
      roundedRect(doc, L, y - 2, 20, 20, 4, COLOR.primary);
      doc
        .fontSize(9)
        .fillColor(COLOR.white)
        .font("Helvetica-Bold")
        .text(String(idx + 1), L, y + 3, { width: 20, align: "center" });

      doc
        .fontSize(10)
        .fillColor(COLOR.dark)
        .font("Helvetica")
        .text(rec, L + 28, y, { width: PAGE_W - 28 });
      doc.moveDown(0.5);
    });

    // ── FOOTER ───────────────────────────────────────────────────────────────
    const footerY = doc.page.height - 50;
    doc
      .moveTo(L, footerY)
      .lineTo(L + PAGE_W, footerY)
      .lineWidth(0.5)
      .strokeColor(COLOR.border)
      .stroke();

    doc
      .fontSize(8)
      .fillColor(COLOR.muted)
      .font("Helvetica")
      .text(
        "This report is generated automatically by Limbu AI using your Google Business Profile data.\n" +
          "For support visit limbu.ai",
        L,
        footerY + 8,
        { width: PAGE_W, align: "center" }
      );

    doc.end();
  });
}

// ── Helper extractors ────────────────────────────────────────────────────────

function extractIssues(raw) {
  if (!raw) return [];
  if (Array.isArray(raw.issues))        return raw.issues.slice(0, 8).map(String);
  if (Array.isArray(raw.problems))      return raw.problems.slice(0, 8).map(String);
  if (Array.isArray(raw.missing))       return raw.missing.slice(0, 8).map(String);
  if (Array.isArray(raw.improvements))  return raw.improvements.slice(0, 8).map(String);

  // Try to build from flags
  const flags = [];
  if (!raw.hasPhotos       && raw.hasPhotos       !== undefined) flags.push("No business photos uploaded");
  if (!raw.hasHours        && raw.hasHours        !== undefined) flags.push("Business hours not set");
  if (!raw.hasDescription  && raw.hasDescription  !== undefined) flags.push("Business description missing");
  if (!raw.hasWebsite      && raw.hasWebsite      !== undefined) flags.push("Website URL not added");
  if (!raw.hasPhone        && raw.hasPhone        !== undefined) flags.push("Phone number missing");
  if (!raw.isVerified      && raw.isVerified      !== undefined) flags.push("Profile not verified");
  return flags;
}

function extractRecommendations(raw, score) {
  if (!raw) return defaultRecs(score);
  if (Array.isArray(raw.recommendations)) return raw.recommendations.slice(0, 6).map(String);
  if (Array.isArray(raw.suggestions))     return raw.suggestions.slice(0, 6).map(String);
  if (Array.isArray(raw.tips))            return raw.tips.slice(0, 6).map(String);
  return defaultRecs(score);
}

function defaultRecs(score) {
  const recs = [
    "Add high-quality photos of your business, products, and team.",
    "Respond to all customer reviews within 24 hours.",
    "Keep your business hours accurate and up to date.",
    "Write a detailed and keyword-rich business description.",
    "Add your website URL and primary phone number.",
    "Enable Google Messaging to chat with customers directly.",
  ];
  if (score !== null && score >= 80) {
    return [
      "Maintain consistent posting (at least 2 Google Posts per week).",
      "Use Q&A section to address common customer questions.",
      "Add product/service catalog with prices.",
      "Monitor and respond to all new reviews promptly.",
    ];
  }
  return recs;
}

// ── Text summary builder ─────────────────────────────────────────────────────

/**
 * Build a plain-text summary of the health score for chatbot display.
 *
 * @param {object} opts
 * @returns {string}
 */
export function buildHealthScoreText(opts) {
  const {
    businessName = "Your Business",
    score        = null,
    rawData      = {},
  } = opts;

  const style  = scoreStyle(score ?? 0);
  const issues = extractIssues(rawData);
  const recs   = extractRecommendations(rawData, score);

  const lines = [
    `📊 *GMB Health Score Report — ${businessName}*`,
    ``,
    `🏆 *Score: ${score !== null ? `${score}/100` : "N/A"} (${style.label})*`,
  ];

  if (rawData.rating)       lines.push(`⭐ Rating: ${rawData.rating} / 5.0`);
  if (rawData.totalReviews) lines.push(`💬 Total Reviews: ${rawData.totalReviews}`);
  if (rawData.profileCompleteness) lines.push(`✅ Profile Completeness: ${rawData.profileCompleteness}%`);

  if (issues.length) {
    lines.push(``, `⚠️ *Issues Found:*`);
    issues.slice(0, 5).forEach((issue, i) => lines.push(`  ${i + 1}. ${issue}`));
  }

  if (recs.length) {
    lines.push(``, `💡 *Top Recommendations:*`);
    recs.slice(0, 4).forEach((rec, i) => lines.push(`  ${i + 1}. ${rec}`));
  }

  lines.push(``, `📄 Full PDF report is attached below.`);

  return lines.join("\n");
}
