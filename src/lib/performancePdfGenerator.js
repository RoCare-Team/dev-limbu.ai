import jsPDF from "jspdf";
import { toast } from "react-hot-toast";
import { toCanvas } from "html-to-image";

/**
 * Generate a professional performance insights PDF report
 * Using html-to-image which supports modern CSS (oklch) better than html2canvas
 */
export const generatePerformanceInsightsPDF = async (reportElement, reportMetadata) => {
  const { businessName, locationName, reportMonth, reportYear } = reportMetadata;
  const toastId = "pdf-generation";

  try {
    toast.loading("Generating Professional PDF...", { id: toastId });

    if (!reportElement) {
      throw new Error("Report element not found");
    }

    // Ensure the element is fully visible for capture
    const originalStyle = reportElement.style.cssText;
    
    // Temporarily adjust styles for better capture if needed
    // reportElement.style.height = 'auto';
    // reportElement.style.overflow = 'visible';

    // Capture report as canvas
    const canvas = await toCanvas(reportElement, {
      backgroundColor: "#ffffff",
      pixelRatio: 2,
      skipFonts: false,
      cacheBust: true,
      // Ensure we capture the full scroll height
      height: reportElement.scrollHeight,
      width: reportElement.scrollWidth,
    });

    // Restore original styles
    reportElement.style.cssText = originalStyle;

    const imgData = canvas.toDataURL("image/png");
    const imgWidth = 210; // A4 width in mm
    const pageHeightPdf = 297; // A4 height in mm
    const imgHeight = (canvas.height * imgWidth) / canvas.width;

    const pdf = new jsPDF("p", "mm", "a4");

    let heightLeft = imgHeight;
    let position = 0;

    // Add first page
    pdf.addImage(imgData, "PNG", 0, position, imgWidth, imgHeight, undefined, 'FAST');
    heightLeft -= pageHeightPdf;

    // Add additional pages if needed
    while (heightLeft > 0) {
      position = heightLeft - imgHeight;
      pdf.addPage();
      pdf.addImage(imgData, "PNG", 0, position, imgWidth, imgHeight, undefined, 'FAST');
      heightLeft -= pageHeightPdf;
    }

    // Add footer to all pages
    const pageCount = pdf.getNumberOfPages();
    for (let i = 1; i <= pageCount; i++) {
      pdf.setPage(i);
      pdf.setFontSize(8);
      pdf.setTextColor(128, 128, 128);
      pdf.text(
        `Generated by Limbu AI | ${businessName} | Page ${i} of ${pageCount}`,
        10,
        pageHeightPdf - 7
      );
    }

    // Generate filename
    const sanitizedBusinessName = businessName.replace(/[^a-z0-9]/gi, "-").toLowerCase();
    const filename = `performance_report_${sanitizedBusinessName}_${reportMonth}_${reportYear}.pdf`;

    pdf.save(filename);
    toast.success("PDF Downloaded Successfully!", { id: toastId });
  } catch (error) {
    console.error("PDF generation error:", error);
    toast.error(`Failed to generate PDF: ${error.message || "Unknown error"}`, { id: toastId });
    throw error;
  }
};

/**
 * Build the same performance insights PDF but return it as a base64 string
 * (without the data-URI prefix) instead of triggering a download.
 * Used for emailing the report as an attachment.
 */
export const buildPerformanceInsightsPdfBase64 = async (reportElement, reportMetadata = {}) => {
  const { businessName = "Business" } = reportMetadata;

  if (!reportElement) {
    throw new Error("Report element not found");
  }

  const canvas = await toCanvas(reportElement, {
    backgroundColor: "#ffffff",
    pixelRatio: 2,
    skipFonts: false,
    cacheBust: true,
    height: reportElement.scrollHeight,
    width: reportElement.scrollWidth,
  });

  const imgData = canvas.toDataURL("image/png");
  const imgWidth = 210; // A4 width in mm
  const pageHeightPdf = 297; // A4 height in mm
  const imgHeight = (canvas.height * imgWidth) / canvas.width;

  const pdf = new jsPDF("p", "mm", "a4");

  let heightLeft = imgHeight;
  let position = 0;

  pdf.addImage(imgData, "PNG", 0, position, imgWidth, imgHeight, undefined, "FAST");
  heightLeft -= pageHeightPdf;

  while (heightLeft > 0) {
    position = heightLeft - imgHeight;
    pdf.addPage();
    pdf.addImage(imgData, "PNG", 0, position, imgWidth, imgHeight, undefined, "FAST");
    heightLeft -= pageHeightPdf;
  }

  const pageCount = pdf.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    pdf.setPage(i);
    pdf.setFontSize(8);
    pdf.setTextColor(128, 128, 128);
    pdf.text(
      `Generated by Limbu AI | ${businessName} | Page ${i} of ${pageCount}`,
      10,
      pageHeightPdf - 7
    );
  }

  // datauristring -> strip the "data:application/pdf;filename=...;base64," prefix
  const dataUri = pdf.output("datauristring");
  return dataUri.includes(",") ? dataUri.split(",")[1] : dataUri;
};

export default generatePerformanceInsightsPDF;
