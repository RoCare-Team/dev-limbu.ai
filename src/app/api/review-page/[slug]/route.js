import { MongoClient } from "mongodb";
import { generateUniversalSlug, stringToSlug } from "@/utils/slugify";
import { findAllSuccessfulGmbLocations } from "@/lib/gmbSessionStore";

function getClientPromise() {
  const uri = process.env.MONGODB_URI;
  if (!uri) throw new Error("Please define MONGODB_URI in .env");
  if (!global._reviewPageClientPromise) {
    global._reviewPageClientPromise = new MongoClient(uri).connect();
  }
  return global._reviewPageClientPromise;
}

// Legacy helper — kept only for pre-existing printed QR codes generated before
// the resolver was unified with generateUniversalSlug().
function createSlug(str) {
  return stringToSlug(str);
}

/**
 * Best identifier for the conflict-disambiguation suffix — mirrors
 * getLocationIdentifier() in useMagicQR.js / chatbotActionHandlers.js exactly,
 * so a slug generated by either flow resolves here.
 */
function getLocationIdentifier(listing) {
  return (listing?.locationId || listing?.name || listing?.locationResourceName || "").toString();
}

/**
 * Score how well `slug` matches this listing.
 *   10 → exact match against the CURRENT slug generator (with or without the
 *        conflict-suffix) — this is what /get-magic-qr and the chatbot's
 *        magic_qr action both produce today via generateUniversalSlug().
 *    4-2 → legacy formats / prefix fallback, for QR codes printed before
 *        the unification (kept so old codes in the field keep working).
 */
function scoreSlugMatch(slug, listing) {
  const title = listing.title || "";
  const locality =
    listing.storefrontAddress?.locality ||
    listing.address?.locality ||
    listing.locality ||
    listing.profile?.address?.locality ||
    "";
  const addressLines = listing.storefrontAddress?.addressLines || listing.address?.addressLines || [];
  const firstLineAddress =
    listing.addressLine || addressLines[0] || "";

  const idPart = getLocationIdentifier(listing).substring(0, 5);

  // ── Current format — single source of truth, same fn used by both flows ──
  const currentSlug = generateUniversalSlug(listing);
  if (slug === currentSlug || slug === `${currentSlug}-${idPart}`) {
    return 10;
  }

  // ── Legacy formats (pre-unification QR codes) ────────────────────────────
  let subLocality = "";
  if (addressLines.length > 0) {
    const lastLine = addressLines[addressLines.length - 1] || "";
    const parts = lastLine.split(",").map((p) => p.trim()).filter(Boolean);
    if (parts.length > 0) subLocality = parts[parts.length - 1];
  }
  const oldShortSlug = createSlug(`${title}-${locality}`);
  const oldLongSlug = createSlug(`${title}-${locality}${firstLineAddress ? `-${firstLineAddress}` : ""}`);
  const legacyUniversalSlug = createSlug(`${title}-${locality}${subLocality ? `-${subLocality}` : ""}`);

  if (
    slug === oldShortSlug || slug === `${oldShortSlug}-${idPart}` ||
    slug === oldLongSlug || slug === `${oldLongSlug}-${idPart}` ||
    slug === legacyUniversalSlug || slug === `${legacyUniversalSlug}-${idPart}`
  ) {
    return 9;
  }

  if (oldLongSlug.startsWith(slug)) return 4;
  if (currentSlug.startsWith(slug)) return 3;
  if (oldShortSlug.startsWith(slug)) return 2;

  return 0;
}

/** Search dashboard-connected businesses (AdminBusiness → "adminbusinesses" collection). */
async function findInAdminBusinesses(slug) {
  const client = await getClientPromise();
  const db = client.db("test");
  const collection = db.collection("adminbusinesses");

  const businesses = await collection.find({}).toArray();

  let bestMatch = null;
  let matchedAccountName = "";
  let highestScore = 0;

  for (const business of businesses) {
    if (!Array.isArray(business.listings)) continue;

    for (const listing of business.listings) {
      if (!listing.title) continue;

      const score = scoreSlugMatch(slug, listing);
      if (score > highestScore) {
        highestScore = score;
        bestMatch = listing;
        matchedAccountName = business.accountName || "";
      }
      if (highestScore === 10) break;
    }
    if (highestScore === 10) break;
  }

  if (!bestMatch) return null;

  return {
    title: bestMatch.title || "",
    locality: bestMatch.storefrontAddress?.locality || "",
    locationId: bestMatch.name || "",
    placeId: bestMatch.metadata?.placeId || "",
    newReviewUri: bestMatch.metadata?.newReviewUri || null,
    accountName: matchedAccountName,
    primaryCategory: bestMatch.categories?.primaryCategory?.displayName || "",
    additionalCategories: bestMatch.categories?.additionalCategories?.map((cat) => cat.displayName) || [],
    websiteUri: bestMatch.websiteUri || null,
    accountId: bestMatch.accountId || null,
    phoneNumbers: bestMatch.phoneNumbers || null,
    storefrontAddress: bestMatch.storefrontAddress || null,
  };
}

/**
 * Backfill a missing Google review link by locationResourceName — covers
 * chatbot-connected businesses saved before `metadata.newReviewUri` capture
 * was added, where the SAME location also exists in AdminBusiness (dashboard
 * sync) with the metadata already present.
 */
async function backfillReviewUriByLocationResourceName(locationResourceName) {
  if (!locationResourceName) return null;
  try {
    const client = await getClientPromise();
    const db = client.db("test");
    const collection = db.collection("adminbusinesses");

    const business = await collection.findOne(
      { "listings.name": locationResourceName },
      { projection: { "listings.$": 1 } }
    );
    return business?.listings?.[0]?.metadata?.newReviewUri || null;
  } catch (err) {
    console.warn("⚠️ backfillReviewUriByLocationResourceName failed:", err.message);
    return null;
  }
}

/** Fallback: search chatbot-connected businesses (GMBConnection.locationsData). */
async function findInChatbotConnections(slug) {
  const flattened = await findAllSuccessfulGmbLocations();

  let bestMatch = null;
  let highestScore = 0;

  for (const { location } of flattened) {
    if (!location?.title) continue;
    const score = scoreSlugMatch(slug, location);
    if (score > highestScore) {
      highestScore = score;
      bestMatch = location;
    }
    if (highestScore === 10) break;
  }

  if (!bestMatch) return null;

  let newReviewUri =
    bestMatch.newReviewUri ||
    (bestMatch.placeId ? `https://search.google.com/local/writereview?placeid=${bestMatch.placeId}` : null);

  // Legacy chatbot connection (saved before metadata capture) — try the
  // same location's AdminBusiness record as a last resort.
  if (!newReviewUri) {
    newReviewUri = await backfillReviewUriByLocationResourceName(bestMatch.locationResourceName);
  }

  return {
    title: bestMatch.title || "",
    locality: bestMatch.locality || "",
    locationId: bestMatch.locationResourceName || "",
    placeId: bestMatch.placeId || "",
    newReviewUri,
    accountName: "",
    primaryCategory: (bestMatch.categories || [])[0] || "",
    additionalCategories: (bestMatch.categories || []).slice(1),
    websiteUri: bestMatch.websiteUri || null,
    accountId: bestMatch.accountId || null,
    phoneNumbers: bestMatch.primaryPhone ? { primaryPhone: bestMatch.primaryPhone } : null,
    storefrontAddress: {
      locality: bestMatch.locality || "",
      addressLines: bestMatch.addressLine ? [bestMatch.addressLine] : [],
    },
  };
}

export async function GET(req, context) {
  try {
    const params = await context?.params;
    let slug = params?.slug;

    if (!slug) {
      const pathname = req.nextUrl.pathname;
      slug = pathname.split("/").pop();
    }

    slug = decodeURIComponent(slug || "").trim();

    if (!slug) {
      return Response.json({ error: "Slug is required" }, { status: 400 });
    }

    console.log("🔍 Incoming slug:", slug);

    // 1. Dashboard-connected businesses first (AdminBusiness)
    let result = await findInAdminBusinesses(slug);

    // 2. Fallback — chatbot-connected businesses (GMBConnection), same slug logic
    if (!result) {
      result = await findInChatbotConnections(slug);
    }

    if (!result) {
      return Response.json(
        { error: "Business location not found", slug },
        { status: 404 }
      );
    }

    return Response.json(result);
  } catch (error) {
    console.error("❌ Review API Error:", error);

    return Response.json(
      { error: "Internal Server Error" },
      { status: 500 }
    );
  }
}
