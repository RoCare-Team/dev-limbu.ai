import jsPDF from "jspdf";
import { toast } from "react-hot-toast";
import html2canvas from "html2canvas";

/**
 * Generate a professional performance insights PDF report with better design
 */
export const generatePerformanceInsightsPDF = async (reportElement, reportMetadata) => {
  const { businessName, locationName, reportMonth, reportYear, startDate, endDate } = reportMetadata;
  const toastId = "pdf-generation";

  try {
    toast.loading("Generating Professional PDF...", { id: toastId });

    if (!reportElement) {
      throw new Error("Report element not found");
    }

    // Capture report as canvas
    const canvas = await html2canvas(reportElement, {
      backgroundColor: "#ffffff",
      scale: 2,
      logging: false,
      allowTaint: true,
      useCORS: true,
    });

    const imgData = canvas.toDataURL("image/png");
    const imgWidth = 210; // A4 width in mm
    const pageHeight = 297; // A4 height in mm
    const imgHeight = (canvas.height * imgWidth) / canvas.width;

    const pdf = new jsPDF("p", "mm", "a4");
    const pageWidth = pdf.internal.pageSize.getWidth();
    const pageHeightPdf = pdf.internal.pageSize.getHeight();

    let heightLeft = imgHeight;
    let position = 0;

    // Add first page
    pdf.addImage(imgData, "PNG", 0, 0, imgWidth, imgHeight);
    heightLeft -= pageHeightPdf;

    // Add additional pages if needed
    while (heightLeft >= 0) {
      position = heightLeft - imgHeight;
      pdf.addPage();
      pdf.addImage(imgData, "PNG", 0, position, imgWidth, imgHeight);
      heightLeft -= pageHeightPdf;
    }

    // Add footer to all pages
    const pageCount = pdf.getNumberOfPages();
    for (let i = 1; i <= pageCount; i++) {
      pdf.setPage(i);
      pdf.setFontSize(8);
      pdf.setTextColor(128, 128, 128);
      pdf.text(
        `Generated by Limbu AI | Page ${i} of ${pageCount} | ${new Date().toLocaleDateString()}`,
        10,
        pageHeightPdf - 5
      );
    }

    // Generate filename
    const sanitizedBusinessName = businessName.replace(/[^a-z0-9]/gi, "-").toLowerCase();
    const sanitizedLocationName = locationName.replace(/[^a-z0-9]/gi, "-").toLowerCase();
    const filename = `${sanitizedBusinessName}_${sanitizedLocationName}_performance_report_${reportMonth}_${reportYear}.pdf`;

    pdf.save(filename);
    toast.success("PDF Downloaded Successfully!", { id: toastId });
  } catch (error) {
    console.error("PDF generation error:", error);
    toast.error("Failed to generate PDF: " + error.message, { id: toastId });
    throw error;
  }
};

export default generatePerformanceInsightsPDF;
