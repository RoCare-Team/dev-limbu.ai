/**
 * GET /api/automation-queue-status
 *
 * READ-ONLY. Shows how many posts are still waiting for IMAGE GENERATION
 * (i.e. their AutomationPlan slot is reserved but no Post document exists
 * yet — that only happens once /api/cron/automation-fill-queue succeeds).
 * This is the "generation queue" — distinct from /api/post-status?status=scheduled,
 * which only shows posts that ALREADY finished generating and are waiting to
 * be published.
 *
 * Mirrors the exact due-time logic in /api/cron/automation-fill-queue so the
 * numbers here always match what that cron will actually do on its next run.
 *
 * Query params (all optional):
 *   userId=<USR...>   restrict to one user's plan
 *
 * Response:
 *   {
 *     success: true,
 *     totals: { plans, pendingSlots, overdueSlots, upcomingSlots },
 *     plans: [
 *       {
 *         planId, userId, businessName,
 *         postIndex, postLimit, pending,       // pending = postLimit - postIndex
 *         overdue,                             // slots already due (should have generated by now)
 *         upcoming,                            // slots not due yet
 *         nextDueAt, nextPublishAt,            // next slot's timing
 *       }, ...
 *     ]
 *   }
 */
import { NextResponse } from 'next/server';
import dbConnect from '@/lib/dbConnect';
import AutomationPlan from '@/models/AutomationPlan';

const DAY_MS = 86400000;

export async function GET(request) {
  await dbConnect();
  const now = new Date();
  const { searchParams } = new URL(request.url);
  const userId = searchParams.get('userId');

  const query = {
    active:            true,
    automationEnabled: true,
    postQueueMode:     'delay_generate_publish',
    $or: [
      { 'queueTiming.publishSchedule.0': { $exists: true } },
      { 'queueTiming.publishStartAt':    { $exists: true } },
      { 'queueTiming.generateStartAt':   { $exists: true } },
    ],
    $expr: { $lt: ['$postIndex', '$queueTiming.postLimit'] },
  };
  if (userId) query.userId = userId;

  const plans = await AutomationPlan.find(query).sort({ updatedAt: 1 }).lean();

  const result = [];
  let totalPending = 0, totalOverdue = 0, totalUpcoming = 0;

  for (const plan of plans) {
    const t = plan.queueTiming || {};
    const stepDays = Number(t.stepDays) || 1;
    const publishAfterMin = Number(t.publishAfterMin) || 24 * 60;
    const sched = Array.isArray(t.publishSchedule) ? t.publishSchedule : [];
    const postIndex = plan.postIndex || 0;
    const postLimit = Number(t.postLimit) || 0;
    const pending = Math.max(0, postLimit - postIndex);

    let overdue = 0;
    let nextDueAt = null;
    let nextPublishAt = null;

    for (let idx = postIndex; idx < postLimit; idx++) {
      let publishAt, dueAt;
      if (sched.length > 0) {
        if (idx >= sched.length) break; // no more slots scheduled
        publishAt = new Date(sched[idx]);
        dueAt = new Date(publishAt.getTime() - publishAfterMin * 60 * 1000);
      } else if (t.publishStartAt) {
        const pubStart = new Date(t.publishStartAt).getTime();
        publishAt = new Date(pubStart + idx * stepDays * DAY_MS);
        dueAt = new Date(publishAt.getTime() - publishAfterMin * 60 * 1000);
      } else if (t.generateStartAt) {
        const startTs = new Date(t.generateStartAt).getTime();
        dueAt = new Date(startTs + idx * stepDays * DAY_MS);
        publishAt = new Date(dueAt.getTime() + publishAfterMin * 60 * 1000);
      } else {
        break; // no anchor at all
      }

      if (idx === postIndex) {
        nextDueAt = dueAt;
        nextPublishAt = publishAt;
      }
      if (dueAt <= now) overdue++;
    }

    const upcoming = Math.max(0, pending - overdue);
    totalPending += pending;
    totalOverdue += overdue;
    totalUpcoming += upcoming;

    const loc0 = Array.isArray(plan.locations) && plan.locations[0] ? plan.locations[0] : null;

    result.push({
      planId:      plan._id,
      userId:      plan.userId,
      businessName: loc0?.name || plan.businessName || '',
      frequency:   plan.frequency || 'daily',
      postIndex,
      postLimit,
      pending,
      overdue,   // should already have generated by now — this is the real backlog
      upcoming,  // scheduled for later, not due yet — normal
      nextDueAt,
      nextPublishAt,
    });
  }

  return NextResponse.json({
    success: true,
    timestamp: now.toISOString(),
    totals: {
      plans: result.length,
      pendingSlots:  totalPending,
      overdueSlots:  totalOverdue,   // > 0 means the fill-queue cron is behind
      upcomingSlots: totalUpcoming,
    },
    plans: result,
  });
}
